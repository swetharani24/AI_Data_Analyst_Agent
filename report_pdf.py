
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer
)


def generate_pdf_report(report_items):

    # Create PDF in memory
    pdf_buffer = BytesIO()

    document = SimpleDocTemplate(
        pdf_buffer,
        pagesize=A4,
        rightMargin=0.7 * inch,
        leftMargin=0.7 * inch,
        topMargin=0.7 * inch,
        bottomMargin=0.7 * inch
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        fontSize=20,
        alignment=TA_CENTER,
        textColor=colors.darkblue,
        spaceAfter=20
    )

    heading_style = ParagraphStyle(
        "ReportHeading",
        parent=styles["Heading2"],
        fontSize=13,
        textColor=colors.darkblue,
        spaceBefore=12,
        spaceAfter=8
    )

    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["BodyText"],
        fontSize=9,
        leading=14,
        spaceAfter=8
    )

    story = []

    story.append(
        Paragraph(
            "AI-Powered Data Analysis Report",
            title_style
        )
    )

    story.append(
        Paragraph(
            "Generated by AI Data Analyst Multi-Agent System",
            body_style
        )
    )

    story.append(Spacer(1, 15))

    for item in report_items:

        item = str(item)

        if item.strip() == "AI-Generated Business Report:":
            story.append(
                Paragraph(
                    "AI-Generated Business Report",
                    heading_style
                )
            )
            continue

        # Preserve line breaks and safely format text
        safe_text = escape(item).replace("\n", "<br/>")

        story.append(
            Paragraph(safe_text, body_style)
        )

    document.build(story)

    pdf_buffer.seek(0)

    return pdf_buffer.getvalue()
